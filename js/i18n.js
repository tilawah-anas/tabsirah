const I18N_STORAGE_KEY = "tabsirah-lang";

function applyLanguage(lang) {
  const dict = translations[lang];
  if (!dict) return;

  // Text content
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  // Placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });

  // Aria labels
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria;
    if (dict[key] !== undefined) el.setAttribute("aria-label", dict[key]);
  });

  // Document direction & lang
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  // Update the toggle label to reflect the CURRENT language
  const label = document.getElementById("lang-label");
  if (label) label.textContent = lang === "ar" ? "ع" : "EN";

  try {
    localStorage.setItem(I18N_STORAGE_KEY, lang);
  } catch (e) {
  }
}

function getCurrentLanguage() {
  return document.documentElement.lang === "ar" ? "ar" : "en";
}

function toggleLanguage() {
  applyLanguage(getCurrentLanguage() === "ar" ? "en" : "ar");
}

document.addEventListener("DOMContentLoaded", () => {
  const toggle = document.getElementById("lang-toggle");
  if (toggle) toggle.addEventListener("click", toggleLanguage);

  let saved = "en";
  try {
    saved = localStorage.getItem(I18N_STORAGE_KEY) || "en";
  } catch (e) {
  }
  applyLanguage(saved);
});